def main():
    OUT.mkdir(parents=True, exist_ok=True)
    write_tokens()
    records = []
    for family in FAMILIES:
        for theme in PALETTES:
            for mobile in (False, True):
                name = f"{family}{'-mobile' if mobile else ''}-{theme}-static.svg"
                data = globals()[family](theme, mobile).encode()
                path = OUT / name
                path.write_bytes(data)
                records.append({"path": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(data).hexdigest(),
                                "bytes": len(data), "theme": theme, "mobile": mobile, "motion": "none"})
    manifest = {"families": list(FAMILIES), "generator": "design/readme-refresh/build_profile_assets.py",
                "font": "type/provenance.json", "assets": records}
    (HERE / "profile-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Built {len(records)} static profile assets")


if __name__ == "__main__":
    main()
