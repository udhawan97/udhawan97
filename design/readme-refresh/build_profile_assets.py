"""Build the profile's static artwork from local, licensed glyph outlines."""

from __future__ import annotations

import hashlib
import html
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / "assets" / "profile-studio"
TYPE = json.loads((HERE / "type" / "glyphs.json").read_text())

# Tokens resolve to literal SVG paints: GitHub image proxies need no CSS or fonts.
PALETTES = {
    "light": dict(bg="#EEF2F0", panel="#E2EAE5", ink="#173C35", muted="#426159",
                  rule="#B7C7C0", accent="#CEDD71", accent_ink="#203E30"),
    "dark": dict(bg="#111F1C", panel="#1B3029", ink="#E3ECE6", muted="#A7BFB4",
                 rule="#3D5C4F", accent="#D2E582", accent_ink="#203E30"),
}
FAMILIES = ("masthead", "maintenance")
FONTS = {"label": "Arial, Helvetica, sans-serif"}


def write_tokens():
    names = {"bg": "paper", "panel": "panel", "ink": "ink", "muted": "muted",
             "rule": "rule", "accent": "accent", "accent_ink": "accent-ink"}
    def block(theme):
        return '\n'.join(f'  --color-art-{name}: {PALETTES[theme][key].lower()};' for key, name in names.items())
    (ROOT / "tokens.css").write_text('''/* Hallmark · pre-emit critique: P5 H5 E4 S5 R4 V5 */
/* Hallmark · macrostructure: Marquee Hero · static typographic masthead
 * theme: custom · vibe: graphic portfolio, precise and quietly confident
 * display: Bricolage Grotesque (outlined) · body: GitHub host typography
 * axes: cool-light / heavy-grotesque / citrus · context: user-directed
 * Generated by design/readme-refresh/build_profile_assets.py.
 */
:root {
''' + block("light") + '''
  --font-display: "Bricolage Grotesque", sans-serif;
  --font-art-label: Arial, Helvetica, sans-serif;
  --font-body: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;
  --space-art-unit: 8px;
  --text-art-display: 174px;
  --rule-art: 1px;
  --dur-art: 0ms;
}
@media (prefers-color-scheme: dark) {
  :root {
''' + block("dark") + '''
  }
}
''')


class Art:
    def __init__(self, width, height, theme, title, description):
        self.width, self.height = width, height
        self.colors = PALETTES[theme]
        self.parts = []
        self.glyphs = set()
        self.title, self.description = title, description

    def rect(self, x, y, width, height, color, **attrs):
        extra = " ".join(f'{key}="{value}"' for key, value in attrs.items())
        self.parts.append(f'<rect x="{x}" y="{y}" width="{width}" height="{height}" fill="{self.colors[color]}" {extra}/>')

    def line(self, x1, y1, x2, y2, color="rule", width=1):
        self.parts.append(f'<path d="M{x1} {y1}H{x2}" fill="none" stroke="{self.colors[color]}" stroke-width="{width}"/>' if y1 == y2 else f'<path d="M{x1} {y1}L{x2} {y2}" fill="none" stroke="{self.colors[color]}" stroke-width="{width}"/>')

    def label(self, value, x, y, size=18, color="muted", weight=500):
        self.parts.append(f'<text x="{x}" y="{y}" font-family="{FONTS["label"]}" font-size="{size}" font-weight="{weight}" fill="{self.colors[color]}">{html.escape(value)}</text>')

    def display(self, value, x, y, size, color="ink", tracking=0):
        self.parts.append(f'<g aria-label="{html.escape(value)}" data-font-size="{size}" fill="{self.colors[color]}">')
        for char in value:
            glyph = TYPE["glyphs"][char]
            self.glyphs.add(char)
            self.parts.append(f'<use href="#g{ord(char)}" transform="translate({x:.3f} {y}) scale({size / 1000} {-size / 1000})"/>')
            x += glyph["advance"] * size / 1000 + tracking
        self.parts.append('</g>')

    def monogram(self, x, y, scale=1):
        c = self.colors
        self.parts.append(f'''<g transform="translate({x} {y}) scale({scale})" aria-hidden="true">
<path d="M30 12V142C30 227 152 227 152 142V12" fill="none" stroke="{c['ink']}" stroke-width="42"/>
<path d="M138 12H179C301 12 301 214 179 214H138" fill="none" stroke="{c['ink']}" stroke-width="42"/>
<path d="M138 12H179C224 12 254 40 267 76" fill="none" stroke="{c['accent']}" stroke-width="42"/>
<path d="M130 99H174" stroke="{c['bg']}" stroke-width="13"/>
<path d="M130 121H174" stroke="{c['bg']}" stroke-width="13"/>
</g>''')

    def svg(self):
        defs = ''.join(f'<path id="g{ord(c)}" d="{TYPE["glyphs"][c]["path"]}"/>' for c in sorted(self.glyphs))
        return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" height="{self.height}" viewBox="0 0 {self.width} {self.height}" role="img" aria-labelledby="title desc">
<title id="title">{html.escape(self.title)}</title>
<desc id="desc">{html.escape(self.description)}</desc>
<defs>{defs}</defs>
{''.join(self.parts)}
</svg>
'''


def masthead(theme, mobile):
    w, h = (400, 432) if mobile else (1000, 448)
    a = Art(w, h, theme, "Umang Dhawan — product thinking, engineering care",
            "An interlocking U and D mark pairs with Umang Dhawan's name. Chicago. Consulting and independent open-source work.")
    a.rect(0, 0, w, h, "bg")
    if mobile:
        a.label("CHICAGO / INDEPENDENT WORK", 24, 35, 18)
        a.display("UMANG", 20, 117, 86, tracking=-1.2)
        a.display("DHAWAN", 20, 190, 86, tracking=-1.2)
        a.monogram(269, 258, .34)
        a.display("Product", 24, 277, 34)
        a.display("thinking.", 24, 315, 34)
        a.display("Engineering", 24, 363, 34)
        a.display("care.", 24, 401, 34)
    else:
        a.label("CHICAGO / CONSULTING + OPEN SOURCE", 40, 40, 20)
        a.display("UMANG", 32, 190, 174, tracking=-2.5)
        a.display("DHAWAN", 32, 333, 174, tracking=-2.5)
        a.monogram(710, 99, .78)
        a.line(40, 362, 960, 362)
        a.display("Product thinking. Engineering care.", 40, 414, 37, tracking=-.25)
    return a.svg()


